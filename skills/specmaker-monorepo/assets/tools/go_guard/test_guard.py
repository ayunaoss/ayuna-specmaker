from pathlib import Path

from guard import ALLOW_BARE_GO, scan_root


def write(root: Path, relative: str, text: str) -> Path:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def test_bare_go_is_rejected(tmp_path: Path) -> None:
    write(tmp_path, "apps/x/main.go", "package x\n\nfunc f() {\n\tgo func() {}()\n}\n")

    problems = scan_root(tmp_path)

    assert len(problems) == 1
    assert problems[0].line == 4
    assert "bare go" in problems[0].message


def test_bare_go_in_test_is_allowed(tmp_path: Path) -> None:
    write(tmp_path, "apps/x/main_test.go", "package x\n\nfunc f() {\n\tgo func() {}()\n}\n")

    assert scan_root(tmp_path) == []


def test_bare_go_allow_directive(tmp_path: Path) -> None:
    write(
        tmp_path,
        "apps/x/main.go",
        f"package x\n\nfunc f() {{\n\t{ALLOW_BARE_GO}: one server lifecycle\n\tgo serve()\n"
        f"\tgo run() {ALLOW_BARE_GO}: ticker tied to ctx\n}}\n",
    )

    assert scan_root(tmp_path) == []


def test_allow_directive_covers_only_its_own_statement(tmp_path: Path) -> None:
    write(
        tmp_path,
        "apps/x/main.go",
        f"package x\n\n{ALLOW_BARE_GO}: one server lifecycle\nfunc f() {{\n\tgo serve()\n\tgo other()\n}}\n",
    )

    assert [p.line for p in scan_root(tmp_path)] == [5, 6]


def test_allow_directive_needs_a_reason(tmp_path: Path) -> None:
    write(tmp_path, "apps/x/main.go", f"package x\n\nfunc f() {{\n\t{ALLOW_BARE_GO}\n\tgo serve()\n}}\n")

    assert len(scan_root(tmp_path)) == 1


def test_comment_markers_inside_strings_do_not_hide_code(tmp_path: Path) -> None:
    write(
        tmp_path,
        "apps/x/main.go",
        'package x\n\nvar s = "/*"\nvar u = "http://x"\n\nfunc f() {\n\tgo func() {}()\n}\n',
    )

    assert [p.line for p in scan_root(tmp_path)] == [7]


def test_raw_strings_are_not_code(tmp_path: Path) -> None:
    write(
        tmp_path,
        "apps/x/main.go",
        "package x\n\nconst script = `\ngo func() {}\nsync.WaitGroup\n`\n\nfunc f() {\n\tgo work()\n}\n",
    )

    assert [p.line for p in scan_root(tmp_path)] == [9]


def test_generated_file_is_skipped(tmp_path: Path) -> None:
    write(
        tmp_path,
        "bufgen/go/x/x.pb.go",
        "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n\nfunc f() { go func() {}() }\n",
    )

    assert scan_root(tmp_path) == []


def test_waitgroup_is_rejected_even_in_test(tmp_path: Path) -> None:
    write(
        tmp_path,
        "libs/x/main_test.go",
        "package x\n\nimport \"sync\"\n\nvar wg sync.WaitGroup\n",
    )

    problems = scan_root(tmp_path)

    assert len(problems) == 1
    assert "sync.WaitGroup" in problems[0].message


def test_errgroup_is_rejected(tmp_path: Path) -> None:
    write(
        tmp_path,
        "libs/x/main.go",
        "package x\n\nfunc f() { _ = errgroup.Group{} }\n",
    )

    problems = scan_root(tmp_path)

    assert len(problems) == 1
    assert "errgroup" in problems[0].message


def test_conc_usage_passes(tmp_path: Path) -> None:
    write(
        tmp_path,
        "libs/x/main.go",
        "package x\n\nfunc f() {\n\tvar wg conc.WaitGroup\n\twg.Go(func() {})\n\twg.Wait()\n}\n",
    )

    assert scan_root(tmp_path) == []


def test_block_comments_do_not_trigger(tmp_path: Path) -> None:
    write(
        tmp_path,
        "apps/x/main.go",
        "package x\n\n/*\ngo func() {}\nsync.WaitGroup\nerrgroup.Group\n*/\n",
    )

    assert scan_root(tmp_path) == []


def test_comments_do_not_trigger(tmp_path: Path) -> None:
    write(
        tmp_path,
        "apps/x/main.go",
        "package x\n\n// go func() is not allowed.\n// sync.WaitGroup is not allowed.\n",
    )

    assert scan_root(tmp_path) == []


def test_custom_roots(tmp_path: Path) -> None:
    write(tmp_path, "services/x/main.go", "package x\n\nfunc f() {\n\tgo func() {}()\n}\n")

    assert scan_root(tmp_path, ("services",)) != []
